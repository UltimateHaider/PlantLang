'use strict';
const INNATE={
  math:{
    SQRT:([a])=>Math.sqrt(+a),
    ABS:([a])=>Math.abs(+a),
    CEIL:([a])=>Math.ceil(+a),
    FLOOR:([a])=>Math.floor(+a),
    ROUND:([a,b=0])=>parseFloat((+a).toFixed(+b)),
    RANDOM:([lo,hi])=>Math.floor(Math.random()*(+hi-+lo+1))+ +lo,
    POW:([a,b])=>Math.pow(+a,+b),
    LOG:([a])=>parseFloat(Math.log(+a).toFixed(6)),
    SIN:([a])=>parseFloat(Math.sin(+a).toFixed(6)),
    COS:([a])=>parseFloat(Math.cos(+a).toFixed(6)),
    PI:()=>Math.PI,
    E:()=>Math.E,
    SIGN:([a])=>Math.sign(+a),
    CLAMP:([a,lo,hi])=>Math.min(Math.max(+a,+lo),+hi),
  },
  strings:{
    UPPER:([s])=>String(s).toUpperCase(),
    LOWER:([s])=>String(s).toLowerCase(),
    TRIM:([s])=>String(s).trim(),
    LENGTH:([s])=>String(s).length,
    REVERSE:([s])=>String(s).split('').reverse().join(''),
    REPEAT:([s,n])=>String(s).repeat(+n),
    PAD_LEFT:([s,len,ch='0'])=>String(s).padStart(+len,ch),
    PAD_RIGHT:([s,len,ch=' '])=>String(s).padEnd(+len,ch),
    INCLUDES:([s,sub])=>String(s).includes(sub),
    STARTS_WITH:([s,sub])=>String(s).startsWith(sub),
    ENDS_WITH:([s,sub])=>String(s).endsWith(sub),
    SPLIT:([s,sep])=>String(s).split(sep),
    REPLACE:([s,from,to])=>String(s).replaceAll(from,to),
    SLICE:([s,a,b])=>String(s).slice(+a,b!==undefined?+b:undefined),
    FIND:([s,sub])=>String(s).indexOf(sub),
    COUNT_OF:([s,sub])=>String(s).split(sub).length-1,
    JOIN:([arr,sep=''])=>Array.isArray(arr)?arr.join(sep):String(arr),
  },
  lists:{
    UNIQUE:([arr])=>arr?[...new Set(arr)]:[],
    REVERSE:([arr])=>arr?[...arr].reverse():[],
    FLATTEN:([arr])=>arr?arr.flat(Infinity):[],
    SORT:([arr])=>arr?[...arr].sort((a,b)=>typeof a==='number'&&typeof b==='number'?a-b:String(a).localeCompare(String(b))):[],
    CHUNK:([arr,n])=>{if(!arr)return[];const r=[];for(let i=0;i<arr.length;i+=+n)r.push(arr.slice(i,i+ +n));return r;},
    ZIP:([a,b])=>a?a.map((v,i)=>[v,b&&b[i]]):[],
    AVERAGE:([arr])=>arr&&arr.length?arr.reduce((s,v)=>s+(+v),0)/arr.length:0,
    MEDIAN:([arr])=>{if(!arr||!arr.length)return 0;const s=[...arr].sort((a,b)=>a-b);const m=Math.floor(s.length/2);return s.length%2?s[m]:(s[m-1]+s[m])/2;},
    FILTER_GT:([arr,v])=>arr?arr.filter(x=>+x>+v):[],
    FILTER_LT:([arr,v])=>arr?arr.filter(x=>+x<+v):[],
    INCLUDES:([arr,v])=>Array.isArray(arr)&&arr.includes(v),
    INDEX_OF:([arr,v])=>Array.isArray(arr)?arr.indexOf(v):-1,
    RANGE:([from,to,step=1])=>{const r=[];for(let i=+from;i<=+to;i+=+step)r.push(i);return r;},
  },
  io:{
    NOW:()=>new Date().toLocaleString('ar-IQ'),
    STAMP:()=>Date.now(),
    DATE:()=>new Date().toLocaleDateString('ar-IQ'),
    TIME:()=>new Date().toLocaleTimeString('ar-IQ'),
    YEAR:()=>new Date().getFullYear(),
  },
  fs:{
    READ:([path])=>{try{return require('fs').readFileSync(path,'utf8');}catch(e){return null;}},
    WRITE:([path,content])=>{require('fs').writeFileSync(path,String(content),'utf8');return true;},
    APPEND:([path,line])=>{require('fs').appendFileSync(path,String(line)+'\n','utf8');return true;},
    EXISTS:([path])=>require('fs').existsSync(path),
  },
};
module.exports={INNATE};
